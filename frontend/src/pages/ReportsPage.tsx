import React, { useState } from 'react';
import { Download } from 'lucide-react';
import { Header } from '../components/layout/Header';
import { useAppStore } from '../data/store';
import './ReportsPage.css';

export const ReportsPage: React.FC = () => {
  const { detections, brand } = useAppStore();

  const [dateRange, setDateRange] = useState('Last 7 days (6 to 12 Oct 2026)');
  const [includeProfiles, setIncludeProfiles] = useState(true);
  const [includeBrandPages, setIncludeBrandPages] = useState(true);
  const [includeScamAccounts, setIncludeScamAccounts] = useState(true);
  const [includeApps, setIncludeApps] = useState(true);
  const [statusFilter, setStatusFilter] = useState('All statuses');
  const [includeEvidence, setIncludeEvidence] = useState(true);
  const [exportFormat, setExportFormat] = useState<'PDF' | 'CSV'>('PDF');
  const [generating, setGenerating] = useState(false);

  const [recentExports, setRecentExports] = useState([
    {
      filename: 'acme-bank-detections-2026-10-05.pdf',
      meta: 'PDF · 238 KB · Harini · 5 Oct',
    },
    {
      filename: 'acme-bank-weekly-2026-09-28.csv',
      meta: 'CSV · 12 KB · Harini · 28 Sep',
    },
    {
      filename: 'acme-bank-detections-2026-09-21.pdf',
      meta: 'PDF · 191 KB · Harini · 21 Sep',
    },
  ]);

  const handleGenerate = () => {
    setGenerating(true);
    setTimeout(() => {
      setGenerating(false);
      const newFileName = `acme-bank-report-2026-10-12.${exportFormat.toLowerCase()}`;
      setRecentExports([
        {
          filename: newFileName,
          meta: `${exportFormat} · 245 KB · Harini · Just now`,
        },
        ...recentExports,
      ]);
      alert(`Report generated: ${newFileName}. File is ready to download.`);
    }, 1200);
  };

  const handleDownload = (filename: string) => {
    const element = document.createElement('a');
    const file = new Blob([`Report export for ${brand.name}: ${filename}\nGenerated by ScamMind AI`], {
      type: 'text/plain',
    });
    element.href = URL.createObjectURL(file);
    element.download = filename;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <>
      <Header
        title="Reports"
        subtitle="Export detections with reasons and evidence for your team or the platforms"
      />

      <div className="panel-content">
        <div className="pdf-reports-wrap">
          {/* Top 2-Column Split */}
          <div className="reports-top-split">
            {/* Left: Export Form */}
            <div className="card export-form-card">
              <h3 className="panel-card-title">Export detections</h3>

              <div className="export-field">
                <label className="export-lbl">Date range</label>
                <select
                  className="export-select"
                  value={dateRange}
                  onChange={(e) => setDateRange(e.target.value)}
                >
                  <option value="Last 7 days (6 to 12 Oct 2026)">
                    Last 7 days (6 to 12 Oct 2026)
                  </option>
                  <option value="Last 30 days">Last 30 days</option>
                  <option value="Quarter to date">Quarter to date</option>
                </select>
              </div>

              {/* Include checkboxes */}
              <div className="export-field">
                <label className="export-lbl">Include</label>
                <div className="checkbox-column">
                  <label className="chk-label">
                    <input
                      type="checkbox"
                      checked={includeProfiles}
                      onChange={(e) => setIncludeProfiles(e.target.checked)}
                      className="chk-input"
                    />
                    <span>Fake profiles</span>
                  </label>

                  <label className="chk-label">
                    <input
                      type="checkbox"
                      checked={includeBrandPages}
                      onChange={(e) => setIncludeBrandPages(e.target.checked)}
                      className="chk-input"
                    />
                    <span>Fake brand pages</span>
                  </label>

                  <label className="chk-label">
                    <input
                      type="checkbox"
                      checked={includeScamAccounts}
                      onChange={(e) => setIncludeScamAccounts(e.target.checked)}
                      className="chk-input"
                    />
                    <span>Scam accounts</span>
                  </label>

                  <label className="chk-label">
                    <input
                      type="checkbox"
                      checked={includeApps}
                      onChange={(e) => setIncludeApps(e.target.checked)}
                      className="chk-input"
                    />
                    <span>Fake apps</span>
                  </label>
                </div>
              </div>

              {/* Status */}
              <div className="export-field">
                <label className="export-lbl">Status</label>
                <select
                  className="export-select"
                  value={statusFilter}
                  onChange={(e) => setStatusFilter(e.target.value)}
                >
                  <option value="All statuses">All statuses</option>
                  <option value="New only">New only</option>
                  <option value="Reviewing only">Reviewing only</option>
                  <option value="Confirmed only">Confirmed only</option>
                </select>
              </div>

              {/* Evidence checkbox */}
              <div className="export-field">
                <label className="chk-label">
                  <input
                    type="checkbox"
                    checked={includeEvidence}
                    onChange={(e) => setIncludeEvidence(e.target.checked)}
                    className="chk-input"
                  />
                  <span>Include evidence (screenshots, URLs, hashes)</span>
                </label>
              </div>

              {/* Format pills */}
              <div className="export-field">
                <label className="export-lbl">Format</label>
                <div className="format-toggle-row">
                  <button
                    type="button"
                    className={`format-toggle-btn ${exportFormat === 'PDF' ? 'active' : ''}`}
                    onClick={() => setExportFormat('PDF')}
                  >
                    PDF report
                  </button>
                  <button
                    type="button"
                    className={`format-toggle-btn ${exportFormat === 'CSV' ? 'active' : ''}`}
                    onClick={() => setExportFormat('CSV')}
                  >
                    CSV data
                  </button>
                </div>
              </div>

              <button
                type="button"
                className="btn-primary generate-btn"
                onClick={handleGenerate}
                disabled={generating}
              >
                {generating ? 'Generating…' : 'Generate report'}
              </button>
            </div>

            {/* Right: Preview Dossier */}
            <div className="card report-preview-card">
              <div className="preview-card-header">
                <div className="preview-title-row">
                  <div className="report-doc-badge">A</div>
                  <div>
                    <h3 className="preview-doc-title">Brand Protection Report</h3>
                    <div className="preview-doc-sub">
                      Acme Bank · 6 to 12 Oct 2026 · Preview
                    </div>
                  </div>
                </div>

                <span className="sample-data-chip">Sample data</span>
              </div>

              {/* Top stats bar */}
              <div className="report-stats-grid">
                <div className="report-stat-cell">
                  <span className="stat-value">11</span>
                  <span className="stat-desc">Detections</span>
                </div>
                <div className="report-stat-cell">
                  <span className="stat-value">6</span>
                  <span className="stat-desc">Social</span>
                </div>
                <div className="report-stat-cell">
                  <span className="stat-value">5</span>
                  <span className="stat-desc">Apps</span>
                </div>
                <div className="report-stat-cell">
                  <span className="stat-value">2</span>
                  <span className="stat-desc">Confirmed</span>
                </div>
                <div className="report-stat-cell">
                  <span className="stat-value">7</span>
                  <span className="stat-desc">Official, excluded</span>
                </div>
              </div>

              {/* Detections Preview Table */}
              <div className="preview-table-wrap">
                <table className="preview-table">
                  <thead>
                    <tr>
                      <th style={{ width: '36px' }}>#</th>
                      <th>Name or handle</th>
                      <th>Platform</th>
                      <th>Type</th>
                      <th>Score</th>
                      <th>Status</th>
                    </tr>
                  </thead>
                  <tbody>
                    {detections.map((det, index) => (
                      <tr key={det.id}>
                        <td className="row-num-cell">{index + 1}</td>
                        <td className="row-name-cell">{det.handleOrPackage || det.name}</td>
                        <td className="cell-muted">{det.platform}</td>
                        <td className="cell-muted">{det.type.replace('_', ' ')}</td>
                        <td className="row-score-cell">{det.score}</td>
                        <td>
                          <span
                            className={`chip ${
                              det.status === 'New'
                                ? 'chip-blue'
                                : det.status === 'Reviewing'
                                ? 'chip-orange'
                                : det.status === 'Confirmed'
                                ? 'chip-red'
                                : 'chip-green'
                            }`}
                          >
                            {det.status}
                          </span>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          </div>

          {/* Bottom Recent Exports */}
          <div className="card recent-exports-card">
            <h3 className="panel-card-title">Recent exports</h3>

            <div className="recent-exports-list">
              {recentExports.map((exp, idx) => (
                <div key={idx} className="recent-export-item">
                  <div className="export-file-info">
                    <span className="export-filename">{exp.filename}</span>
                    <span className="export-filemeta">{exp.meta}</span>
                  </div>

                  <button
                    type="button"
                    className="btn-secondary btn-sm download-btn"
                    onClick={() => handleDownload(exp.filename)}
                  >
                    <Download size={13} />
                    <span>Download</span>
                  </button>
                </div>
              ))}
            </div>
          </div>

          <div className="page-bottom-note">
            Sample data for the fictional brand Acme Bank. Not real detections.
          </div>
        </div>
      </div>
    </>
  );
};
