"""Generate docs/DATABASE_SCHEMA.md (tables, columns, keys, indexes, ER diagram) and docs/schema.sql (PostgreSQL DDL) from the models.

Run from backend/:  python -m scripts.export_schema
The files are derived, never edited by hand: change the models, add an Alembic migration, then re-run this.
"""
from __future__ import annotations

from pathlib import Path

from sqlalchemy import UniqueConstraint
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

import app.models  # noqa: F401  (registers every table on Base.metadata)
from app.db.base import Base

DOCS = Path(__file__).resolve().parents[2] / "docs"

PURPOSE = {
    "users": "People who can sign in (admin, analyst, viewer). The first admin is seeded from ADMIN_EMAIL / ADMIN_PASSWORD.",
    "refresh_tokens": "Rotating refresh tokens (hashed). Reuse of a rotated token revokes the user's tokens.",
    "brands": "The protected brand of ONE account (owner_id): name, description, aliases, keywords, domains, logo and verification summary.",
    "brand_logos": "Extra official logos per brand. A candidate image is compared with all of them.",
    "brand_publishers": "Official publisher / developer identifiers per app store.",
    "official_accounts": "Official social handles. Anything listed here is never flagged (allowlist).",
    "official_apps": "Official app listings (package / bundle id, store ids, publisher). Also allowlisted.",
    "asset_verifications": "Human attestation that an official asset is verified (method, who, when).",
    "detections": "Candidate impersonations with score, band, severity, reasons, evidence and review status.",
    "detection_events": "Timeline of every status change, note and re-score on a detection.",
    "official_matches": "Candidates excluded because they matched an official asset, with the matched rule.",
    "candidate_images": "Images uploaded with manual or imported candidates (safe re-encoded copies).",
    "scans": "Scan runs: state, progress, counts, per-source report and timings.",
    "sources": "Per-platform source health: status, last sync, message, monitored flag.",
    "collector_state": "Collector health, back-off schedule and last good cached results.",
    "api_usage": "Monthly provider credit / request counters (Tavily credits, Safe Browsing requests).",
    "settings": "Key / value application settings (data mode, schedule, sensitivity, active text provider...).",
    "reports": "Draft and approved reports built from selected detections. Nothing is sent automatically.",
    "lookalike_cases": "Labelled name cases for the Look-alike Lab test runner, per brand (brand_id).",
    "studio_items": "Items a user saved in Brand Studio (logo, palette, name, content, audit, sentiment), owner-only.",
    "text_analysis_cache": "Cached results of hosted AI text analysis, keyed by a hash of model, prompt and text.",
    "audit_log": "Who did what and when, for every mutating action.",
}


def col_type(c) -> str:
    return str(c.type.compile(dialect=postgresql.dialect()))


def main() -> None:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    out = ["# BrandShield database schema", "",
           "Generated by `python -m scripts.export_schema` from the SQLAlchemy models (PostgreSQL types). Do not edit by hand.",
           "The live Supabase/PostgreSQL database matches these models (`alembic check` reports no differences). SQL: [schema.sql](schema.sql).", "",
           f"**{len(tables)} tables** plus Alembic's own `alembic_version`. Row-level security is enabled on every table (the API connects as the database owner, which bypasses it; Supabase's public REST key sees nothing).", "",
           "## Tables", "", "| Table | Purpose |", "|---|---|"]
    out += [f"| [`{t.name}`](#{t.name}) | {PURPOSE.get(t.name, '')} |" for t in tables]
    out += ["", "## Relationships", "", "```mermaid", "erDiagram"]
    for t in tables:
        for fk in t.foreign_keys:
            out.append(f"    {fk.column.table.name} ||--o{{ {t.name} : \"{fk.parent.name}\"")
    out += ["```", ""]
    for t in tables:
        out += [f"## {t.name}", "", PURPOSE.get(t.name, ""), "", "| Column | Type | Null | Default | Notes |", "|---|---|---|---|---|"]
        for c in t.columns:
            notes = []
            if c.primary_key:
                notes.append("PK")
            for fk in c.foreign_keys:
                notes.append(f"FK -> {fk.column.table.name}.{fk.column.name}" + (f" ({fk.ondelete})" if fk.ondelete else ""))
            if c.unique:
                notes.append("unique")
            default = ""
            if c.server_default is not None:
                default = f"`{getattr(c.server_default.arg, 'text', c.server_default.arg)}`"
            elif c.default is not None and getattr(c.default, "is_scalar", False):
                default = f"`{c.default.arg}` (app)"
            out.append(f"| `{c.name}` | {col_type(c)} | {'yes' if c.nullable else 'no'} | {default} | {', '.join(notes)} |")
        extras = [f"unique ({', '.join(c.name for c in k.columns)})" for k in t.constraints if isinstance(k, UniqueConstraint)]
        extras += [("unique " if i.unique else "") + f"index `{i.name}` ({', '.join(c.name for c in i.columns)})" for i in sorted(t.indexes, key=lambda i: i.name or "")]
        if extras:
            out += ["", "Constraints and indexes: " + "; ".join(extras)]
        out.append("")
    (DOCS / "DATABASE_SCHEMA.md").write_text("\n".join(out), encoding="utf-8", newline="\n")

    ddl = ["-- BrandShield schema (PostgreSQL). Generated by python -m scripts.export_schema; migrations in backend/alembic are the source of truth.", ""]
    for t in tables:
        ddl.append(str(CreateTable(t).compile(dialect=postgresql.dialect())).strip() + ";\n")
        for i in sorted(t.indexes, key=lambda i: i.name or ""):
            ddl.append(str(CreateIndex(i).compile(dialect=postgresql.dialect())).strip() + ";")
        ddl.append("")
    (DOCS / "schema.sql").write_text("\n".join(ddl), encoding="utf-8", newline="\n")
    print(f"wrote {DOCS / 'DATABASE_SCHEMA.md'} and {DOCS / 'schema.sql'} ({len(tables)} tables)")


if __name__ == "__main__":
    main()
